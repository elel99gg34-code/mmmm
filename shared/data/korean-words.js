const WORD_SET = new Set(WORDS);

/** Is `word` in the built-in dictionary? */
export function isKnownWord(word) {
  return WORD_SET.has(word);
}

/** Every dictionary word starting with one of `starts`. */
export function wordsStartingWith(starts) {
  const set = starts instanceof Set ? starts : new Set(starts);
  return WORDS.filter((w) => set.has(w[0]));
}
